-- 판정 항목별 설명과 불변 검토 이벤트.
-- finding은 consistency_json 안에 있으므로 서비스가 같은 버전에서 ID의 존재를 검증한다.
BEGIN;

CREATE TABLE judge.explanations (
    explanation_id TEXT PRIMARY KEY CHECK (btrim(explanation_id) <> ''),
    job_id TEXT NOT NULL,
    version INTEGER NOT NULL,
    finding_id TEXT NOT NULL CHECK (
        finding_id ~ '^m[0-9]+/(F2|F2L|F15|F15DG|FPT):[^[:space:]]+$'
    ),
    status TEXT NOT NULL CHECK (status IN ('작성 중', '완료', '실패')),
    source TEXT CHECK (source IN ('llm', 'template')),
    checked BOOLEAN,
    payload_json JSONB CHECK (payload_json IS NULL OR jsonb_typeof(payload_json) = 'object'),
    input_sha256 TEXT CHECK (input_sha256 IS NULL OR input_sha256 ~ '^[0-9a-f]{64}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT explanations_version_fk FOREIGN KEY (job_id, version)
        REFERENCES judge.versions (job_id, version),
    CONSTRAINT explanations_one_per_finding UNIQUE (job_id, version, finding_id),
    CONSTRAINT explanations_complete CHECK (
        status <> '완료' OR (
            source IS NOT NULL AND checked IS NOT NULL AND payload_json IS NOT NULL
            AND input_sha256 IS NOT NULL
            AND payload_json ?& ARRAY['summary', 'reasons', 'basis']
            AND jsonb_typeof(payload_json->'summary') = 'string'
            AND jsonb_typeof(payload_json->'reasons') = 'array'
            AND jsonb_typeof(payload_json->'basis') = 'array'
        )
    )
);
CREATE INDEX explanations_input_idx ON judge.explanations (input_sha256)
    WHERE input_sha256 IS NOT NULL;

CREATE TABLE judge.reviews (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (event_id > 0),
    job_id TEXT NOT NULL,
    version INTEGER NOT NULL,
    finding_id TEXT NOT NULL CHECK (
        finding_id ~ '^m[0-9]+/(F2|F2L|F15|F15DG|FPT):[^[:space:]]+$'
    ),
    action TEXT NOT NULL CHECK (action IN ('불일치 확정', '예외 승인', '확인', '의견', '되돌리기')),
    comment TEXT CHECK (comment IS NULL OR char_length(comment) <= 2000),
    reviewer TEXT NOT NULL CHECK (char_length(reviewer) BETWEEN 1 AND 50),
    verdict_seen TEXT NOT NULL CHECK (verdict_seen IN ('일치', '불일치', '경계', '근거부족', '참고', '범위 외')),
    review_seq BIGINT NOT NULL CHECK (review_seq > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT reviews_version_fk FOREIGN KEY (job_id, version)
        REFERENCES judge.versions (job_id, version),
    CONSTRAINT reviews_job_event_unique UNIQUE (job_id, event_id),
    CONSTRAINT reviews_job_sequence_unique UNIQUE (job_id, review_seq),
    CONSTRAINT reviews_comment_required CHECK (
        action NOT IN ('예외 승인', '의견') OR (comment IS NOT NULL AND char_length(comment) > 0)
    )
);
CREATE INDEX reviews_finding_idx ON judge.reviews (job_id, finding_id, review_seq DESC);

COMMIT;
